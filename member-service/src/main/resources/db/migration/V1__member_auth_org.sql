CREATE TABLE members (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 email VARCHAR(255) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL,
 display_name VARCHAR(100) NOT NULL,
 email_verified BOOLEAN NOT NULL DEFAULT FALSE,
 platform_admin BOOLEAN NOT NULL DEFAULT FALSE,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE organizations (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 applicant_id BIGINT NOT NULL REFERENCES members(id),
 name VARCHAR(200) NOT NULL,
 kind VARCHAR(16) NOT NULL CHECK (kind IN ('BUILDING','FACTORY')),
 status VARCHAR(24) NOT NULL CHECK (status IN ('PENDING_APPROVAL','ACTIVE','REJECTED')),
 review_reason VARCHAR(500),
 reviewed_by BIGINT REFERENCES members(id),
 reviewed_at TIMESTAMPTZ,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE organization_members (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organization_id BIGINT NOT NULL REFERENCES organizations(id),
 member_id BIGINT NOT NULL REFERENCES members(id),
 role VARCHAR(20) NOT NULL CHECK (role IN ('ADMIN','TECHNICIAN','USER')),
 status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 UNIQUE (organization_id,member_id)
);
CREATE TABLE refresh_sessions (
 id UUID PRIMARY KEY,
 member_id BIGINT NOT NULL REFERENCES members(id),
 token_hash VARCHAR(64) NOT NULL UNIQUE,
 expires_at TIMESTAMPTZ NOT NULL,
 revoked BOOLEAN NOT NULL DEFAULT FALSE,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE audit_logs (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 actor_id BIGINT NOT NULL REFERENCES members(id),
 operation VARCHAR(80) NOT NULL,
 target_type VARCHAR(50) NOT NULL,
 target_id VARCHAR(64) NOT NULL,
 occurred_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_organizations_status ON organizations(status);
CREATE INDEX idx_refresh_member ON refresh_sessions(member_id);
