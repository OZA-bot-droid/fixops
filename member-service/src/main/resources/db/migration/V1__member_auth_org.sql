-- ============================================================================
-- 1. 회원(사용자) 테이블: 플랫폼 전체 사용자 계정 및 권한 정보 관리
-- ============================================================================
CREATE TABLE members (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- 회원 고유 식별자 (자동 증가)
    email VARCHAR(255) NOT NULL UNIQUE,                    -- 로그인용 이메일 (중복 불가)
    password_hash VARCHAR(255) NOT NULL,                   -- 암호화된 비밀번호 해시
    display_name VARCHAR(100) NOT NULL,                    -- 화면 표시 이름 (닉네임/실명)
    email_verified BOOLEAN NOT NULL DEFAULT FALSE,         -- 이메일 인증 완료 여부
    platform_admin BOOLEAN NOT NULL DEFAULT FALSE,         -- 플랫폼 전체 최고 관리자 여부
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()          -- 계정 생성 일시
);

-- ============================================================================
-- 2. 조직(사업장) 테이블: 건물 또는 공장 단위의 가입 신청 및 승인 상태 관리
-- ============================================================================
CREATE TABLE organizations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- 조직 고유 식별자
    applicant_id BIGINT NOT NULL REFERENCES members(id),   -- 조직 등록 최초 신청자 ID (members 참조)
    name VARCHAR(200) NOT NULL,                            -- 조직명 (건물명 또는 공장명)
    kind VARCHAR(16) NOT NULL CHECK (kind IN ('BUILDING', 'FACTORY')), -- 조직 유형 (BUILDING: 건물, FACTORY: 공장)
    status VARCHAR(24) NOT NULL CHECK (status IN ('PENDING_APPROVAL', 'ACTIVE', 'REJECTED')), -- 승인 상태 (PENDING_APPROVAL: 승인대기, ACTIVE: 활성, REJECTED: 반려)
    review_reason VARCHAR(500),                            -- 승인/반려 검토 사유
    reviewed_by BIGINT REFERENCES members(id),             -- 검토 처리한 플랫폼 관리자 ID (members 참조)
    reviewed_at TIMESTAMPTZ,                               -- 검토 처리 완료 일시
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()          -- 조직 신청(생성) 일시
);

-- ============================================================================
-- 3. 조직 구성원 매핑 테이블: 특정 조직에 소속된 회원 및 조직 내 역할 관리
-- ============================================================================
CREATE TABLE organization_members (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- 조직 구성원 매핑 고유 식별자
    organization_id BIGINT NOT NULL REFERENCES organizations(id), -- 소속 조직 ID (organizations 참조)
    member_id BIGINT NOT NULL REFERENCES members(id),      -- 소속 회원 ID (members 참조)
    role VARCHAR(20) NOT NULL CHECK (role IN ('ADMIN', 'TECHNICIAN', 'USER')), -- 조직 내 역할 (ADMIN: 관리자, TECHNICIAN: 기술자/작업자, USER: 일반사용자)
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',          -- 구성원 소속 상태 (기본값: ACTIVE)
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),         -- 조직 합류 일시
    UNIQUE (organization_id, member_id)                    -- 동일 조직 내 동일 회원 중복 등록 방지
);

-- ============================================================================
-- 4. 리프레시 토큰 세션 테이블: 사용자 인증 유지를 위한 토큰 및 만료/폐기 상태 관리
-- ============================================================================
CREATE TABLE refresh_sessions (
    id UUID PRIMARY KEY,                                   -- 세션 고유 식별자 (UUID)
    member_id BIGINT NOT NULL REFERENCES members(id),      -- 세션 소유 회원 ID (members 참조)
    token_hash VARCHAR(64) NOT NULL UNIQUE,                -- 리프레시 토큰 해시값 (중복 불가)
    expires_at TIMESTAMPTZ NOT NULL,                       -- 토큰 만료 일시
    revoked BOOLEAN NOT NULL DEFAULT FALSE,                -- 토큰 강제 폐기(로그아웃 등) 여부
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()          -- 세션 발급 일시
);

-- ============================================================================
-- 5. 감사 로그 테이블: 시스템 내 주요 행위(생성/수정/삭제/승인 등) 이력 추적
-- ============================================================================
CREATE TABLE audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- 감사 로그 고유 식별자
    actor_id BIGINT NOT NULL REFERENCES members(id),       -- 행위 수행자 회원 ID (members 참조)
    operation VARCHAR(80) NOT NULL,                        -- 수행된 작업명 (예: ORG_APPROVED, USER_INVITED)
    target_type VARCHAR(50) NOT NULL,                      -- 작업 대상 리소스 유형 (예: ORGANIZATION, MEMBER)
    target_id VARCHAR(64) NOT NULL,                        -- 작업 대상 리소스 식별자
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT now()         -- 행위 발생 일시
);

-- ============================================================================
-- 6. 인덱스 정의: 조회 성능 최적화
-- ============================================================================
CREATE INDEX idx_organizations_status ON organizations(status); -- 조직 승인 상태별 필터링 조회 속도 향상
CREATE INDEX idx_refresh_member ON refresh_sessions(member_id); -- 특정 회원의 활성 세션 목록 조회 속도 향상
