CREATE TABLE resident_registration_codes (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 roster_entry_id BIGINT NOT NULL REFERENCES roster_entries(id),
 organization_id BIGINT NOT NULL REFERENCES organizations(id),
 complex_id BIGINT NOT NULL REFERENCES apartment_complexes(id),
 code_hash VARCHAR(64) NOT NULL UNIQUE,
 issued_by BIGINT NOT NULL REFERENCES members(id),
 issued_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 expires_at TIMESTAMPTZ NOT NULL,
 consumed_by BIGINT REFERENCES members(id),
 consumed_at TIMESTAMPTZ,
 revoked_at TIMESTAMPTZ,
 CHECK(expires_at > issued_at),
 CHECK((consumed_by IS NULL) = (consumed_at IS NULL)),
 CHECK(consumed_at IS NULL OR revoked_at IS NULL)
);
CREATE UNIQUE INDEX uq_registration_code_open ON resident_registration_codes(roster_entry_id)
 WHERE consumed_at IS NULL AND revoked_at IS NULL;
CREATE INDEX idx_registration_code_scope ON resident_registration_codes(organization_id,complex_id,id);
ALTER TABLE resident_enrollments ALTER COLUMN challenge_id DROP NOT NULL;
ALTER TABLE resident_enrollments ADD COLUMN verification_method VARCHAR(24) NOT NULL DEFAULT 'SMS_OTP';
ALTER TABLE resident_enrollments ADD COLUMN registration_code_id BIGINT UNIQUE REFERENCES resident_registration_codes(id);
ALTER TABLE resident_enrollments ADD CONSTRAINT ck_enrollment_verification_method CHECK (
 (verification_method='SMS_OTP' AND challenge_id IS NOT NULL AND registration_code_id IS NULL)
 OR (verification_method='REGISTRATION_CODE' AND challenge_id IS NULL AND registration_code_id IS NOT NULL
     AND verified_at IS NOT NULL AND status IN ('PENDING_REVIEW','APPROVED','REJECTED'))
);
CREATE TABLE resident_registration_attempts (
 member_id BIGINT PRIMARY KEY REFERENCES members(id),
 window_started_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 attempts INT NOT NULL DEFAULT 0 CHECK(attempts BETWEEN 0 AND 5)
);
