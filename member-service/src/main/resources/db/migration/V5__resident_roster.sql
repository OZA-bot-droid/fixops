CREATE TABLE resident_rosters (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 complex_id BIGINT NOT NULL REFERENCES apartment_complexes(id),
 organization_id BIGINT NOT NULL REFERENCES organizations(id),
 version BIGINT NOT NULL DEFAULT 0,
 status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE' CHECK(status IN ('ACTIVE','INACTIVE')),
 UNIQUE(complex_id,organization_id)
);
CREATE TABLE roster_import_jobs (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 roster_id BIGINT NOT NULL REFERENCES resident_rosters(id),
 organization_id BIGINT NOT NULL REFERENCES organizations(id),
 created_by BIGINT NOT NULL REFERENCES members(id),
 mode VARCHAR(20) NOT NULL CHECK(mode IN ('PARTIAL','FULL')),
 status VARCHAR(20) NOT NULL CHECK(status IN ('STAGING','PREVIEW','COMPLETE','INVALID')),
 file_sha256 VARCHAR(64) NOT NULL,
 base_version BIGINT NOT NULL,
 row_count INT NOT NULL DEFAULT 0,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 committed_at TIMESTAMPTZ,
 UNIQUE(roster_id,file_sha256,base_version,mode)
);
CREATE TABLE roster_staging_rows (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 import_job_id BIGINT NOT NULL REFERENCES roster_import_jobs(id) ON DELETE CASCADE,
 row_no INT NOT NULL,
 building_no VARCHAR(40),
 unit_no VARCHAR(40),
 resident_name VARCHAR(100),
 contact_ciphertext TEXT,
 contact_lookup_hmac VARCHAR(64),
 occupancy_status VARCHAR(20),
 move_in DATE,
 move_out DATE,
 validation_status VARCHAR(20) NOT NULL CHECK(validation_status IN ('VALID','INVALID')),
 error_code VARCHAR(80),
 UNIQUE(import_job_id,row_no)
);
CREATE TABLE roster_entries (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 roster_id BIGINT NOT NULL REFERENCES resident_rosters(id),
 building_no VARCHAR(40) NOT NULL,
 unit_no VARCHAR(40) NOT NULL,
 name VARCHAR(100) NOT NULL,
 contact_ciphertext TEXT NOT NULL,
 contact_lookup_hmac VARCHAR(64) NOT NULL,
 status VARCHAR(20) NOT NULL CHECK(status IN ('ACTIVE','MOVED_OUT')),
 location_id BIGINT,
 move_in DATE,
 move_out DATE,
 UNIQUE(roster_id,building_no,unit_no,contact_lookup_hmac)
);
CREATE INDEX idx_roster_match ON roster_entries(roster_id,building_no,unit_no,contact_lookup_hmac,status);
CREATE TABLE resident_units (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organization_member_id BIGINT NOT NULL REFERENCES organization_members(id),
 roster_entry_id BIGINT NOT NULL REFERENCES roster_entries(id),
 complex_id BIGINT NOT NULL REFERENCES apartment_complexes(id),
 location_id BIGINT NOT NULL,
 status VARCHAR(20) NOT NULL CHECK(status IN ('ACTIVE','REVOKED')),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 revoked_at TIMESTAMPTZ
);
CREATE UNIQUE INDEX uq_resident_entry_active ON resident_units(roster_entry_id) WHERE status='ACTIVE';
