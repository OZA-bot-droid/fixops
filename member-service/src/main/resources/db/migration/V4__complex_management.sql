CREATE TABLE apartment_complexes (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 kapt_code VARCHAR(40) UNIQUE,
 display_name VARCHAR(200) NOT NULL,
 road_address VARCHAR(500) NOT NULL,
 verification_status VARCHAR(24) NOT NULL CHECK (verification_status IN ('MANUAL_REVIEW','VERIFIED','REJECTED')),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE complex_managements (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 complex_id BIGINT NOT NULL REFERENCES apartment_complexes(id),
 organization_id BIGINT NOT NULL REFERENCES organizations(id),
 status VARCHAR(24) NOT NULL CHECK (status IN ('PENDING_APPROVAL','ACTIVE','REJECTED','ENDED')),
 requested_by BIGINT NOT NULL REFERENCES members(id),
 reviewed_by BIGINT REFERENCES members(id),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 started_at TIMESTAMPTZ,
 ended_at TIMESTAMPTZ,
 CHECK (status <> 'ACTIVE' OR (started_at IS NOT NULL AND ended_at IS NULL)),
 CHECK (status <> 'ENDED' OR (started_at IS NOT NULL AND ended_at IS NOT NULL AND ended_at >= started_at))
);
CREATE UNIQUE INDEX uq_complex_active_management ON complex_managements(complex_id) WHERE status='ACTIVE';
CREATE UNIQUE INDEX uq_complex_pending_management ON complex_managements(complex_id,organization_id) WHERE status='PENDING_APPROVAL';
CREATE TABLE member_complex_access (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organization_member_id BIGINT NOT NULL REFERENCES organization_members(id),
 complex_id BIGINT NOT NULL REFERENCES apartment_complexes(id),
 access_scope VARCHAR(20) NOT NULL CHECK (access_scope IN ('ADMIN','TECHNICIAN','RESIDENT')),
 status VARCHAR(20) NOT NULL CHECK (status IN ('ACTIVE','REVOKED')),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 UNIQUE (organization_member_id,complex_id)
);
CREATE INDEX idx_complex_management_org ON complex_managements(organization_id,status);
CREATE INDEX idx_complex_access_complex ON member_complex_access(complex_id,status);
