CREATE TABLE verification_challenges (
 id UUID PRIMARY KEY,
 member_id BIGINT NOT NULL REFERENCES members(id),
 purpose VARCHAR(20) NOT NULL CHECK(purpose IN ('EMAIL','RESIDENT')),
 destination_key VARCHAR(64) NOT NULL,
 code_hash VARCHAR(64) NOT NULL,
 attempts INT NOT NULL DEFAULT 0 CHECK(attempts BETWEEN 0 AND 5),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 expires_at TIMESTAMPTZ NOT NULL,
 consumed_at TIMESTAMPTZ
);
CREATE INDEX idx_verification_member ON verification_challenges(member_id,purpose,created_at DESC);
CREATE INDEX idx_verification_destination ON verification_challenges(destination_key,purpose,created_at DESC);
CREATE TABLE resident_enrollments (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 member_id BIGINT NOT NULL REFERENCES members(id),
 organization_id BIGINT NOT NULL REFERENCES organizations(id),
 complex_id BIGINT NOT NULL REFERENCES apartment_complexes(id),
 roster_id BIGINT NOT NULL REFERENCES resident_rosters(id),
 building_no VARCHAR(40) NOT NULL,
 unit_no VARCHAR(40) NOT NULL,
 contact_lookup_hmac VARCHAR(64) NOT NULL,
 challenge_id UUID NOT NULL UNIQUE REFERENCES verification_challenges(id),
 status VARCHAR(24) NOT NULL CHECK(status IN ('PENDING_VERIFICATION','PENDING_REVIEW','APPROVED','REJECTED')),
 verified_at TIMESTAMPTZ,
 reviewed_by BIGINT REFERENCES members(id),
 reviewed_at TIMESTAMPTZ,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_enrollment_member ON resident_enrollments(member_id,complex_id,status);
CREATE INDEX idx_enrollment_review ON resident_enrollments(complex_id,status);
