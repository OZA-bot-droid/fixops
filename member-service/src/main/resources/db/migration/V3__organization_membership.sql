ALTER TABLE organization_members ADD CONSTRAINT ck_org_member_status CHECK (status IN ('ACTIVE','INACTIVE'));
CREATE TABLE join_requests (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organization_id BIGINT NOT NULL REFERENCES organizations(id),
 member_id BIGINT NOT NULL REFERENCES members(id),
 status VARCHAR(24) NOT NULL CHECK (status IN ('PENDING_APPROVAL','APPROVED','REJECTED')),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 reviewed_by BIGINT REFERENCES members(id),
 reviewed_at TIMESTAMPTZ
);
CREATE UNIQUE INDEX uq_join_pending ON join_requests(organization_id,member_id) WHERE status='PENDING_APPROVAL';
CREATE TABLE invitations (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organization_id BIGINT NOT NULL REFERENCES organizations(id),
 email VARCHAR(255) NOT NULL,
 token_hash VARCHAR(64) NOT NULL UNIQUE,
 role VARCHAR(20) NOT NULL CHECK (role IN ('USER','TECHNICIAN')),
 created_by BIGINT NOT NULL REFERENCES members(id),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 expires_at TIMESTAMPTZ NOT NULL,
 accepted_at TIMESTAMPTZ,
 accepted_by BIGINT REFERENCES members(id)
);
CREATE INDEX idx_invitation_org ON invitations(organization_id);
CREATE INDEX idx_org_members_active ON organization_members(organization_id,role,status);
