CREATE TABLE organization_onboarding_invitations (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 invitee_email VARCHAR(255) NOT NULL,
 organization_name VARCHAR(200) NOT NULL,
 organization_kind VARCHAR(20) NOT NULL CHECK (organization_kind IN ('BUILDING','FACTORY')),
 created_by BIGINT NOT NULL REFERENCES members(id),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 expires_at TIMESTAMPTZ NOT NULL,
 accepted_at TIMESTAMPTZ,
 accepted_by BIGINT REFERENCES members(id),
 revoked_at TIMESTAMPTZ,
 organization_id BIGINT UNIQUE REFERENCES organizations(id),
 CHECK ((accepted_at IS NULL AND accepted_by IS NULL AND organization_id IS NULL) OR
        (accepted_at IS NOT NULL AND accepted_by IS NOT NULL AND organization_id IS NOT NULL AND revoked_at IS NULL))
);
CREATE INDEX idx_onboarding_email ON organization_onboarding_invitations(invitee_email,expires_at);
CREATE UNIQUE INDEX uq_onboarding_pending ON organization_onboarding_invitations(invitee_email,organization_name,organization_kind)
 WHERE accepted_at IS NULL AND revoked_at IS NULL;
