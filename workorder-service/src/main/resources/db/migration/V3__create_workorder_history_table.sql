-- 3. WORK_ORDER_HISTORY
-- 작업 상태 변경 이력 테이블

CREATE TABLE work_order_history
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- 작업 지시 id
    work_order_id BIGINT      NOT NULL,

    -- 변경 전 작업 상태
    from_status   VARCHAR(30),

    -- 변경 후 작업 상태
    to_status     VARCHAR(30) NOT NULL,

    -- 작업지시의 상태를 변경한 관리자 ID
    changed_by    BIGINT      NOT NULL,

    -- 상태 변경 일시
    created_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    -- 제약 조건
    -- 작업지시 참조 FK
    CONSTRAINT fk_work_order_history_work_order
        FOREIGN KEY (work_order_id)
            REFERENCES work_order (id)
            ON DELETE RESTRICT,


    -- 변경 전 작업 상태 값 제약
    CONSTRAINT chk_history_from_status
        CHECK (
            from_status IS NULL
                OR from_status IN (
                                   'REPORTED',
                                   'ASSIGNED',
                                   'IN_PROGRESS',
                                   'COMPLETED',
                                   'REJECTED',
                                   'CANCELLED'
                )
            ),

    -- 변경 후 작업 상태 값 제약
    CONSTRAINT chk_history_to_status
        CHECK (
            to_status IN (
                          'REPORTED',
                          'ASSIGNED',
                          'IN_PROGRESS',
                          'COMPLETED',
                          'REJECTED',
                          'CANCELLED'
                )
            )
);


-- 인덱스
-- 작업 상태 변경 이력 최신순 조회
CREATE INDEX idx_work_order_history_work_order
    ON work_order_history (work_order_id, created_at DESC);