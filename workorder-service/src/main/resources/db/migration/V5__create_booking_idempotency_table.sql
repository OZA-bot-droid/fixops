-- 5. BOOKING_IDEMPOTENCY
-- 중복 요청 방지 테이블

CREATE TABLE booking_idempotency
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- 작업 지시 id
    work_order_id   BIGINT       NOT NULL,

    -- 클라이언트에서 생성한 요청 고유 키
    request_key     VARCHAR(200) NOT NULL,

    -- 요청 본문을 정규화한 뒤 생성한 해시값(SHA-256 기준)
    request_hash    VARCHAR(64)  NOT NULL,

    -- 조직 id
    organization_id BIGINT       NOT NULL,

    -- 요청한 사용자 id
    actor_id        BIGINT       NOT NULL,

    -- 요청 작업 종류
    operation       VARCHAR(50)  NOT NULL,

    -- 재시도 시 기존 결과 반환을 위한 데이터
    response_status INTEGER,
    response_body   JSONB,

    -- 생성 일자
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT NOW(),

    -- 작업지시 참조 FK
    CONSTRAINT fk_booking_idempotency_work_order
        FOREIGN KEY (work_order_id)
            REFERENCES work_order (id)
            ON DELETE RESTRICT,

    -- 같은 조직·사용자·작업·요청 종류에서 키 중복 방지
    CONSTRAINT uq_booking_idempotency_request
        UNIQUE (
                organization_id,
                actor_id,
                operation,
                request_key
            ),

    -- 빈 요청 키 방지
    CONSTRAINT chk_booking_request_key
        CHECK (LENGTH(TRIM(request_key)) > 0),

    -- 빈 작업 종류 방지
    CONSTRAINT chk_booking_operation
        CHECK (LENGTH(TRIM(operation)) > 0),

    -- SHA-256 해시 형식 검사 (64자리 소문자 16진수)
    CONSTRAINT chk_booking_request_hash
        CHECK (request_hash ~ '^[0-9a-f]{64}$')

);
