-- 2. WORK_ORDER
-- 작업지시 테이블

CREATE TABLE work_order
(
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- 조직 ID
    organization_id       BIGINT       NOT NULL,

    -- 신고 제목
    title                 VARCHAR(200) NOT NULL,

    -- 건물(단지) ID
    complex_id            BIGINT       NOT NULL,

    -- 장소 ID
    location_id           BIGINT       NOT NULL,

    -- 설비 ID
    asset_id              BIGINT,

    -- 신고 내용
    description           TEXT,

    -- 신고자 ID
    reported_by           BIGINT       NOT NULL,

    -- 담당 작업자 ID
    assigned_to           BIGINT,

    -- 작업 우선순위
    priority              VARCHAR(20)  NOT NULL DEFAULT 'MEDIUM',

    -- 작업 상태
    status                VARCHAR(30)  NOT NULL DEFAULT 'REPORTED',

    -- 관련 작업
    related_work_order_id BIGINT,

    -- 동시 수정 방지
    version               BIGINT       NOT NULL DEFAULT 0,

    -- 생성 및 수정 일시
    created_at            TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    updated_at            TIMESTAMPTZ  NOT NULL DEFAULT NOW(),

    -- 자기 참조 FK
    CONSTRAINT fk_work_order_related
        FOREIGN KEY (related_work_order_id)
            REFERENCES work_order (id),

    -- 상태값 제한
    CONSTRAINT chk_work_order_status
        CHECK (
            status IN (
                       'REPORTED',
                       'ASSIGNED',
                       'IN_PROGRESS',
                       'COMPLETED',
                       'REJECTED',
                       'CANCELLED'
                )
            ),

    -- 우선순위 제한
    CONSTRAINT chk_work_order_priority
        CHECK (
            priority IN (
                         'LOW',
                         'MEDIUM',
                         'HIGH',
                         'URGENT'
                )
            ),

    -- 버전 제한
    CONSTRAINT chk_work_order_version
        CHECK (version >= 0)
);


-- 조회 인덱스
-- 조직 및 단지별 조회
CREATE INDEX idx_work_order_org_complex
    ON work_order (organization_id, complex_id);

-- 상태별 조회
CREATE INDEX idx_work_order_status
    ON work_order (status);

-- 신고자별 조회
CREATE INDEX idx_work_order_reported_by
    ON work_order (reported_by);

-- 담당 작업자별 조회
CREATE INDEX idx_work_order_assigned_to
    ON work_order (assigned_to);

-- 생성일 기준 조회
CREATE INDEX idx_work_order_created_at
    ON work_order (created_at DESC);
