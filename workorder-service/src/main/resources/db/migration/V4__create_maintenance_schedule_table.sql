-- 4. MAINTENANCE_SCHEDULE
-- 작업 예약 테이블

-- 1. 예약 시간 중복 검증을 위한 확장 기능
CREATE
EXTENSION IF NOT EXISTS btree_gist;


CREATE TABLE maintenance_schedule
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- 작업 지시 id
    work_order_id BIGINT      NOT NULL,

    -- 작업자 id
    technician_id BIGINT      NOT NULL,

    -- 작업 시작 시간/종료 시간
    start_at      TIMESTAMPTZ NOT NULL,
    end_at        TIMESTAMPTZ NOT NULL,

    -- 작업 상태
    status        VARCHAR(30) NOT NULL DEFAULT 'CONFIRMED',

    -- 생성/수정 일시
    created_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    -- 제약조건
    -- 작업지시 참조 FK
    CONSTRAINT fk_schedule_work_order
        FOREIGN KEY (work_order_id)
            REFERENCES work_order (id)
            ON DELETE RESTRICT,

    -- 작업 상태값 제약
    CONSTRAINT chk_schedule_status
        CHECK (
            status IN (
                       'CONFIRMED',
                       'CANCELLED',
                       'COMPLETED'
                )
            ),

    -- 시작 < 종료 시간 CHECK
    CONSTRAINT chk_schedule_time
        CHECK (start_at < end_at)
);


-- 작업자별 예약 조회
CREATE INDEX idx_schedule_technician
    ON maintenance_schedule (technician_id, start_at);

-- 작업별 예약 조회
CREATE INDEX idx_schedule_work_order
    ON maintenance_schedule (work_order_id);


-- 작업자별 활성 예약 시간 중복 방지
ALTER TABLE maintenance_schedule
    ADD CONSTRAINT no_technician_overlap EXCLUDE USING gist (
    technician_id WITH =,
    tstzrange(start_at, end_at, '[)') WITH &&
)
WHERE (status = 'CONFIRMED');


-- 작업당 활성 확정 예약은 최대 1개
CREATE UNIQUE INDEX uq_active_schedule_per_workorder
    ON maintenance_schedule (work_order_id) WHERE status = 'CONFIRMED';