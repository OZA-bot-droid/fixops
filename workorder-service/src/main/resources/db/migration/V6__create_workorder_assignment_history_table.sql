-- 6. work_order_assignment_history
-- 작업자 변경 이력 테이블

CREATE TABLE work_order_assignment_history
(
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- 작업 지시 id
    work_order_id      BIGINT      NOT NULL,

    -- 변경 전 작업자 id
    from_technician_id BIGINT,

    -- 변경 후 작업자 id
    to_technician_id   BIGINT      NOT NULL,

    -- 작업자를 변경한 관리자 ID
    changed_by         BIGINT      NOT NULL,

    created_at         TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    -- 작업지시 참조 FK
    CONSTRAINT fk_assignment_history_work_order
        FOREIGN KEY (work_order_id)
            REFERENCES work_order (id)
            ON DELETE RESTRICT
);

CREATE INDEX idx_assignment_history_work_order
    ON work_order_assignment_history
        (work_order_id, created_at DESC, id DESC);