ALTER TABLE maintenance_schedule
    ADD CONSTRAINT fk_schedule_current_proposal
        FOREIGN KEY (id, current_proposal_id)
            REFERENCES schedule_proposal (schedule_id, id)
            ON DELETE RESTRICT;


-- =====================================================
-- 9. 예약당 활성 Proposal 최대 1개
-- =====================================================

CREATE UNIQUE INDEX uq_active_proposal_per_schedule
    ON schedule_proposal (schedule_id) WHERE status = 'PENDING';


-- =====================================================
-- 10. 조회 및 만료 처리 인덱스
-- =====================================================

-- 개별 Proposal 만료 대상 조회
CREATE INDEX idx_proposal_expiry
    ON schedule_proposal (expires_at) WHERE status = 'PENDING';


-- 일정 협의 이력 조회
CREATE INDEX idx_proposal_schedule_created
    ON schedule_proposal (
                          schedule_id,
                          created_at ASC,
                          id ASC
        );