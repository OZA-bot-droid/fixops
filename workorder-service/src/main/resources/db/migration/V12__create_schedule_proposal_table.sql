-- =====================================================
-- 7. SCHEDULE_PROPOSAL 생성
-- =====================================================

CREATE TABLE schedule_proposal
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- 예약 ID
    schedule_id     BIGINT      NOT NULL,

    -- 시간을 제안한 회원 ID
    proposed_by     BIGINT      NOT NULL,

    -- 제안 방문 시간
    start_at        TIMESTAMPTZ NOT NULL,
    end_at          TIMESTAMPTZ NOT NULL,

    -- 개별 제안 상태
    status          VARCHAR(30) NOT NULL DEFAULT 'PENDING',

    -- 시간 제안 사유
    reason          TEXT,

    -- 제안 응답 정보
    responded_by    BIGINT,
    responded_at    TIMESTAMPTZ,
    response_reason TEXT,

    -- 개별 제안 응답 기한
    expires_at      TIMESTAMPTZ NOT NULL,

    -- 제안 생성 시각
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),


    -- 예약 참조 FK
    CONSTRAINT fk_proposal_schedule
        FOREIGN KEY (schedule_id)
            REFERENCES maintenance_schedule (id)
            ON DELETE RESTRICT,


    -- 예약 ID와 Proposal ID 복합 참조에 사용
    CONSTRAINT uq_proposal_schedule_id
        UNIQUE (schedule_id, id),


    -- 제안자 ID 검증
    CONSTRAINT chk_proposal_proposed_by
        CHECK (proposed_by > 0),


    -- 응답자 ID 검증
    CONSTRAINT chk_proposal_responded_by
        CHECK (
            responded_by IS NULL
                OR responded_by > 0
            ),


    -- 제안 시간 검증
    CONSTRAINT chk_proposal_time
        CHECK (start_at < end_at),


    -- 제안 상태 검증
    CONSTRAINT chk_proposal_status
        CHECK (
            status IN (
                       'PENDING',
                       'ACCEPTED',
                       'REJECTED',
                       'SUPERSEDED',
                       'CANCELLED',
                       'EXPIRED'
                )
            ),


    -- 응답 기한 검증
    CONSTRAINT chk_proposal_expiry
        CHECK (
            expires_at > created_at
                AND expires_at < start_at
            ),


    -- 응답자와 응답 시각 정합성
    CONSTRAINT chk_proposal_response
        CHECK (
            (
                responded_by IS NULL
                    AND responded_at IS NULL
                )
                OR
            (
                responded_by IS NOT NULL
                    AND responded_at IS NOT NULL
                )
            ),


    -- 제안자 본인의 수락·거절 방지
    CONSTRAINT chk_proposal_response_actor
        CHECK (
            status NOT IN (
                           'ACCEPTED',
                           'REJECTED',
                           'SUPERSEDED'
                )
                OR (
                responded_by IS NOT NULL
                    AND responded_by <> proposed_by
                )
            ),


    -- 거절 사유 필수
    CONSTRAINT chk_proposal_rejection_reason
        CHECK (
            status <> 'REJECTED'
                OR (
                response_reason IS NOT NULL
                    AND LENGTH(TRIM(response_reason)) > 0
                )
            )
);


