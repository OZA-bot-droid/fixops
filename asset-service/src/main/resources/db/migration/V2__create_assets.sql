-- AssetCategory는 산업별 공통 분류이고, 실제 설비는 조직·단지·위치에 귀속된다.
CREATE TABLE asset_category (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    industry_type VARCHAR(20) NOT NULL,
    name VARCHAR(100) NOT NULL,
    CONSTRAINT chk_asset_category_industry CHECK (industry_type IN ('BUILDING', 'FACTORY')),
    CONSTRAINT uq_asset_category_industry_name UNIQUE (industry_type, name)
);

-- 최소 초기 분류. 실제 운영 분류는 추후 관리 기능에서 확장한다.
INSERT INTO asset_category (industry_type, name)
VALUES ('BUILDING', 'GENERAL'), ('FACTORY', 'GENERAL');

CREATE TABLE asset (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL,
    complex_id BIGINT,
    location_id BIGINT NOT NULL,
    category_id BIGINT NOT NULL,
    asset_code VARCHAR(100) NOT NULL,
    name VARCHAR(200) NOT NULL,
    description VARCHAR(2000),
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT fk_asset_location FOREIGN KEY (location_id) REFERENCES location(id),
    CONSTRAINT fk_asset_category FOREIGN KEY (category_id) REFERENCES asset_category(id),
    CONSTRAINT chk_asset_status CHECK (status IN ('ACTIVE', 'INACTIVE')),
    CONSTRAINT chk_asset_complex_scope CHECK (complex_id IS NULL OR complex_id > 0)
);

CREATE INDEX ix_asset_org_complex ON asset (organization_id, complex_id);
CREATE INDEX ix_asset_location ON asset (location_id);
CREATE INDEX ix_asset_category ON asset (category_id);

-- 설비 코드는 조직·단지 범위 안에서 유일하게 관리한다.
CREATE UNIQUE INDEX ux_asset_org_complex_code
    ON asset (organization_id, COALESCE(complex_id, 0), asset_code);
