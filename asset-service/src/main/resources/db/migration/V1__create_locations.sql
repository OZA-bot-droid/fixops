-- Asset 서비스가 소유하는 위치 계층 테이블이다. Member/WorkOrder DB와 물리 FK를 만들지 않는다.
CREATE TABLE location (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL, -- 운영 조직 범위. Member DB의 조직 ID를 논리 참조한다.
    complex_id BIGINT,              -- 아파트 단지 ID. 공장 위치는 NULL일 수 있다.
    parent_id BIGINT,               -- 같은 Asset DB 안의 상위 Location 자기참조 FK.
    location_type VARCHAR(40) NOT NULL,
    code VARCHAR(100) NOT NULL,
    name VARCHAR(200) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT fk_location_parent FOREIGN KEY (parent_id) REFERENCES location(id),
    CONSTRAINT chk_location_status CHECK (status IN ('ACTIVE', 'INACTIVE')),
    CONSTRAINT chk_location_scope CHECK (complex_id IS NULL OR complex_id > 0),
    CONSTRAINT chk_location_not_own_parent CHECK (parent_id IS NULL OR parent_id <> id)
);

-- 조직·단지 범위 조회 및 트리 순회에 쓰는 인덱스.
CREATE INDEX ix_location_org_complex ON location (organization_id, complex_id);
CREATE INDEX ix_location_parent ON location (parent_id);
CREATE INDEX ix_location_org_status ON location (organization_id, status);

-- code는 루트끼리, 자식은 같은 부모 아래에서 조직·단지별로 유일하다.
-- complex_id NULL도 하나의 범위로 취급하도록 0으로 치환한다(실제 ID는 양수).
CREATE UNIQUE INDEX ux_location_root_code
    ON location (organization_id, COALESCE(complex_id, 0), code)
    WHERE parent_id IS NULL;
CREATE UNIQUE INDEX ux_location_child_code
    ON location (organization_id, COALESCE(complex_id, 0), parent_id, code)
    WHERE parent_id IS NOT NULL;
